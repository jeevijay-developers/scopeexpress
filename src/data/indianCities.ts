// Get unique list of states
export const indianStates = [...new Set(indianCities.map(city => city.state))].sort();

// Function to search cities
export function searchCities(query: string, limit: number = 10): City[] {
  if (!query || query.length < 2) return [];
  
  const lowerQuery = query.toLowerCase();
  return indianCities
    .filter(city => city.name.toLowerCase().includes(lowerQuery))
    .slice(0, limit);
}

// Function to get state from city name
export function getStateFromCity(cityName: string): string | undefined {
  const city = indianCities.find(c => c.name.toLowerCase() === cityName.toLowerCase());
  return city?.state;
}
